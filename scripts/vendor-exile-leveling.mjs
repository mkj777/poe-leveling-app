// Copies the route parser from a local clone of HeartofPhos/exile-leveling.
// Usage: node scripts/vendor-exile-leveling.mjs [path-to-clone]
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const UPSTREAM = process.argv[2] ?? path.resolve('..', 'exile-leveling');
const TARGET = path.resolve('src', 'lib', 'exile-leveling');

// data.ts and index.ts are deliberately left out, we write those ourselves.
const FILES = [
  'types.d.ts',
  'route-processing/index.ts',
  'route-processing/patterns.ts',
  'route-processing/scoped-logger.ts',
  'route-processing/gems.ts',
  'route-processing/fragment/index.ts',
  'route-processing/fragment/language.ts'
];

const HEADER = [
  '// Generated by scripts/vendor-exile-leveling.mjs, do not edit.',
  '// Source: https://github.com/HeartofPhos/exile-leveling (MIT)',
  ''
].join('\n');

function stripJsExtensions(source) {
  return source.replace(
    /(from\s+["'])(\.[^"']*?)\.js(["'])/g,
    (_match, head, specifier, tail) => `${head}${specifier}${tail}`
  );
}

const sha = execFileSync('git', ['-C', UPSTREAM, 'rev-parse', 'HEAD'])
  .toString()
  .trim();

for (const file of FILES) {
  const from = path.join(UPSTREAM, 'common', 'src', file);
  const to = path.join(TARGET, file);
  fs.mkdirSync(path.dirname(to), { recursive: true });
  // The type declaration stays untouched; a comment block only gets in the way there.
  const prefix = file.endsWith('.d.ts') ? '' : HEADER;
  fs.writeFileSync(
    to,
    prefix + stripJsExtensions(fs.readFileSync(from, 'utf8')),
    'utf8'
  );
}

fs.writeFileSync(
  path.join(TARGET, 'ATTRIBUTION.md'),
  [
    '# Attribution',
    '',
    'The files in `route-processing/` and `types.d.ts` come from',
    'https://github.com/HeartofPhos/exile-leveling (MIT licence).',
    '',
    `Vendored commit: \`${sha}\``,
    '',
    'Changes compared to the original:',
    '',
    '1. `.js` extensions of relative imports removed so that resolution works',
    '   under `moduleResolution: bundler`.',
    '2. A comment header pointing to origin and generator.',
    '',
    'The code passes the strict type check of this project unchanged,',
    'no `@ts-nocheck` is needed.',
    '',
    'Generated by `scripts/vendor-exile-leveling.mjs`, do not edit by hand.',
    '',
    '`data.ts`, `index.ts` and `build-route.ts` in this directory are our own code.',
    '',
    '## Icons',
    '',
    '`src/assets/exile-leveling/*.png` come from the same project,',
    '`web/src/components/FragmentStep/Fragment/images/`. The colour values in',
    '`src/utilities/fragment-style.ts` follow its `styles.module.css`.',
    ''
  ].join('\n'),
  'utf8'
);

console.log(`vendored ${FILES.length} files from ${sha}`);
